function chunk(type, data) {
  const body = Buffer.concat([Buffer.from(type), data]);
  let crc = 0xffffffff;
  for (const byte of body) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  const size = Buffer.alloc(4), checksum = Buffer.alloc(4);
  size.writeUInt32BE(data.length); checksum.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  return Buffer.concat([size, body, checksum]);
}

function atlas({ colors, pixels }) {
  const width = 384, height = 288, stride = width * 4 + 1;
  const data = Buffer.alloc(stride * height);
  const palette = colors.map((hex) => [...Buffer.from(hex, 'hex'), 255]);
  for (let frame = 0; frame < 4; frame++) {
    for (let y = 0; y < pixels.length; y++) {
      if (pixels[y].length !== 24) throw new Error(`Invalid pixel row: ${pixels[y]}`);
      for (let x = 0; x < 24; x++) {
        const pixel = pixels[y][x];
        if (pixel === '.') continue;
        const color = palette[Number(pixel) - 1];
        if (!color) throw new Error(`Unknown palette entry: ${pixel}`);
        for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 4; dx++) {
          // Column 3 uses the lower head anchor of the splat animation.
          const row = 96 + y * 4 + dy + (frame === 3 ? 40 : 0);
          const offset = row * stride + 1 + (frame * 96 + x * 4 + dx) * 4;
          data.set(color, offset);
        }
      }
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width); header.writeUInt32BE(height, 4);
  header[8] = 8; header[9] = 6;
  return Buffer.concat([
    Buffer.from('89504e470d0a1a0a', 'hex'),
    chunk('IHDR', header), chunk('IDAT', deflateSync(data)), chunk('IEND', Buffer.alloc(0)),
  ]);
}

